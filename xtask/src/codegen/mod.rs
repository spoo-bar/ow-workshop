//! `cargo xtask codegen`: one-time migration of `data/*.json` into checked-in Rust tables.

mod api;
mod enums;
mod naming;
mod settings;
mod signatures;
mod tables;

use std::fs;
use std::path::Path;

use proc_macro2::TokenStream;

use crate::data::Data;

/// Generates `ow-workshop-data/src/generated/*.rs` from the data in `data_dir`.
pub fn run(data_dir: &Path, out_dir: &Path, api_dir: &Path, renames: &Path) -> Result<(), String> {
    let data = Data::load(data_dir)?;
    let mut files = enums::generate(&data)?;
    files.extend(signatures::generate(&data)?);
    files.extend(tables::generate(&data)?);
    files.extend(settings::generate(&data)?);
    files.sort_by_key(|(name, _)| *name);
    files.push(("mod", module_list(files.iter().map(|(name, _)| *name))));

    fs::create_dir_all(out_dir).map_err(|e| format!("{}: {e}", out_dir.display()))?;
    for (name, tokens) in files {
        let path = out_dir.join(format!("{name}.rs"));
        fs::write(&path, format(tokens)?).map_err(|e| format!("{}: {e}", path.display()))?;
    }

    let renames = fs::read_to_string(renames).map_err(|e| format!("{}: {e}", renames.display()))?;
    let renames = api::Renames::parse(&renames)?;
    fs::create_dir_all(api_dir).map_err(|e| format!("{}: {e}", api_dir.display()))?;
    // `Part::Actions` is wired in by the next change.
    let path = api_dir.join("values.rs");
    let values = api::generate(&data, &renames, api::Part::Values)?;
    fs::write(&path, format(values)?).map_err(|e| format!("{}: {e}", path.display()))?;
    Ok(())
}

fn module_list<'a>(names: impl Iterator<Item = &'a str>) -> TokenStream {
    let names: Vec<_> = names.map(|n| quote::format_ident!("{n}")).collect();
    quote::quote! {
        //! Game data tables generated from the bootstrap data.
        #( pub mod #names; )*
    }
}

/// Renders tokens as formatted Rust with a generated-file banner.
fn format(tokens: TokenStream) -> Result<String, String> {
    let file = syn::parse2(tokens).map_err(|e| format!("generated invalid Rust: {e}"))?;
    Ok(format!(
        "// @generated by `cargo xtask codegen`.\n{}",
        prettyplease::unparse(&file)
    ))
}
